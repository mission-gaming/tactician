// said so. Everything else an example computes is the same every time: the
// script is run twice in surroundings chosen to differ (default timezone,
// float precision, locale variables in the environment, a working directory
// outside the repository) and must print the same text both times. PHP does
// not take its numeric locale from the environment unless a script calls
// setlocale(), so the locale variables only catch an example that does;
// the renderer is drawn under a decimal-comma locale in ExampleRendererTest.
// Gap left knowingly: one PHP version per run - the CI matrix (8.3, 8.4,
// 8.5) is what compares versions.
it('prints the same text whatever the timezone, locale, precision and working directory', function (string $example): void {
    $script = ExampleResults::directory() . "/{$example}.php";

    [$plainExit, $plain] = runExampleScript($script, ['error_reporting=-1', 'display_errors=1', 'html_errors=0']);
    [$otherExit, $other] = runExampleScript(
        $script,
        [
            'error_reporting=-1',
            'display_errors=1',
            'html_errors=0',
            'date.timezone=Pacific/Auckland',
            'precision=17',
            'serialize_precision=17',
        ],
        sys_get_temp_dir(),
        ['TZ' => 'Asia/Tokyo', 'LC_ALL' => 'de_DE.UTF-8', 'LANG' => 'de_DE.UTF-8']
    );

    expect($plainExit)->toBe(0)
        ->and($otherExit)->toBe(0);

    if (ExampleResults::containsMeasured(ExampleResults::of($example))) {
        // The measured figures differ by design; everything around them must not
        $withoutFigures = static fn (string $text): string => (string) preg_replace('/[\d.]+ (\w+) \(measured on this run\)/', '$1 (measured)', $text);

        expect($withoutFigures($other))->toBe($withoutFigures($plain))
            ->and($withoutFigures($plain))->not->toBe($plain);

        return;
    }

    expect($other)->toBe($plain);
})->with(ExampleResults::names());

