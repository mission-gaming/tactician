/*
 * Examples are executable documentation and must not ship without
 * validation. Stale examples have shipped fatal errors and false claims
 * before - see the git history for examples 06, 07, 09, 10 and 11.
 *
 * An example computes a named set of results and hands it to
 * Example::present() (examples/support/Example.php), which displays it as a page or as text.
 * The examples are checked on the results, never on the display:
 *
 * 1. Every script in examples/ runs in a PHP process of its own under E_ALL
 *    and must not emit a warning, notice or deprecation.
 * 2. Every example has an entry in $demonstrations below, which asserts on
 *    the objects the example built what the example is there to show. The
 *    assertions are worked out from the schedule, bracket or table itself,
 *    not read back from a number the example reports.
 * 3. tests/Feature/GoldenOutputTest.php pins the whole result set as text
 *    (tests/Fixtures/golden/examples/, regenerated by `composer golden-update`).
 *
 * A new script without an entry here, without a fixture, or missing from
 * examples/README.md and examples/index.php fails the suite.
 *
 * A value that cannot be the same on every run is wrapped in Measured by the
 * example, with the reason. Its fixture line is the unit and the reason, and
 * the example's entry here checks the value itself (example 12).
 *
 * How results are drawn is tested once, in tests/Feature/ExampleRendererTest.php.
 */

