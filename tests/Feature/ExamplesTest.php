/**
 * Run a PHP script in a process of its own and return its exit code and
 * everything it printed, with standard error folded in.
 *
 * @param list<string> $settings `-d` settings, as `name=value`
 * @param array<string, string>|null $environment The whole environment, or null to inherit
 * @return array{int, string}
 *
 * @throws PHPUnit\Framework\AssertionFailedError When the process cannot be started
 */
function runExampleScript(string $script, array $settings, ?string $workingDirectory = null, ?array $environment = null): array
{
    $captured = tempnam(sys_get_temp_dir(), 'example');
    if ($captured === false) {
        Assert::fail('Could not create a temporary file in ' . sys_get_temp_dir());
    }

    $command = [PHP_BINARY];
    foreach ($settings as $setting) {
        $command[] = '-d';
        $command[] = $setting;
    }
    $command[] = $script;

    // Both streams append to one file, so they interleave as they were written
    $process = proc_open(
        $command,
        [1 => ['file', $captured, 'a'], 2 => ['file', $captured, 'a']],
        $pipes,
        $workingDirectory,
        $environment
    );
    if ($process === false) {
        unlink($captured);
        Assert::fail('Could not start PHP to run ' . basename($script));
    }

    $exitCode = proc_close($process);
    $output = (string) file_get_contents($captured);
    unlink($captured);

    return [$exitCode, $output];
}

