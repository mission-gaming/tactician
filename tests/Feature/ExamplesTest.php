/**
 * A named result of an example, checked to be of the expected class.
 *
 * @template T of object
 *
 * @param array<string, mixed> $results
 * @param class-string<T> $class
 * @return T
 *
 * @throws PHPUnit\Framework\Exception
 * @throws PHPUnit\Framework\ExpectationFailedException When the result is missing or of another class
 */
function exampleResult(array $results, string $name, string $class): object
{
    Assert::assertArrayHasKey($name, $results, "The example no longer presents a result named '{$name}'");
    Assert::assertInstanceOf($class, $results[$name], "The result '{$name}' is not a {$class}");

    return $results[$name];
}

/**
 * A named result of an example that is an array.
 *
 * @param array<string, mixed> $results
 * @return array<array-key, mixed>
 *
 * @throws PHPUnit\Framework\Exception
 * @throws PHPUnit\Framework\ExpectationFailedException When the result is missing or not an array
 */
function exampleArray(array $results, string $name): array
{
    Assert::assertArrayHasKey($name, $results, "The example no longer presents a result named '{$name}'");
    Assert::assertIsArray($results[$name], "The result '{$name}' is not an array");

    return $results[$name];
}

/**
 * The ids of an event's participants, sorted, joined by `|`: the same key
 * whichever participant is named first.
 */
function examplePair(Event $event): string
{
    $ids = array_map(static fn (Participant $participant): string => $participant->getId(), $event->getParticipants());
    sort($ids);

    return implode('|', $ids);
}

/**
 * The rounds in which each pair meets, by pair key.
 *
 * @param iterable<Event> $events
 * @return array<string, list<int>>
 */
function exampleMeetings(iterable $events): array
{
    $meetings = [];
    foreach ($events as $event) {
        $meetings[examplePair($event)][] = (int) $event->getRound()?->getNumber();
    }

    return $meetings;
}

/**
 * Assert that a schedule is a complete round robin: every pair of the field
 * meets once in every leg, and nobody plays twice in a round.
 *
 * @throws PHPUnit\Framework\Exception
 * @throws PHPUnit\Framework\ExpectationFailedException When it is not
 */
function assertExampleRoundRobin(Schedule $schedule, int $fieldSize, int $legs = 1): void
{
    $meetings = exampleMeetings($schedule);
    $roundsPerLeg = $fieldSize % 2 === 0 ? $fieldSize - 1 : $fieldSize;

    Assert::assertCount(array_sum(range(1, $fieldSize - 1)), $meetings, 'Not every pair of the field meets');
    foreach ($meetings as $pair => $rounds) {
        Assert::assertCount($legs, $rounds, "{$pair} does not meet once per leg");

        // The meeting in leg k falls within that leg's rounds
        foreach ($rounds as $leg => $round) {
            Assert::assertGreaterThan($leg * $roundsPerLeg, $round, "{$pair} meets twice in one leg");
            Assert::assertLessThanOrEqual(($leg + 1) * $roundsPerLeg, $round, "{$pair} misses a leg");
        }
    }

    foreach ($schedule->getEventsByRound() as $round => $events) {
        $playing = [];
        foreach ($events as $event) {
            foreach ($event->getParticipants() as $participant) {
                $playing[] = $participant->getId();
            }
        }
        Assert::assertSame(array_unique($playing), $playing, "A participant plays twice in round {$round}");
    }
}

